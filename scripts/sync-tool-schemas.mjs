import { readFile, writeFile, mkdir } from 'node:fs/promises'

const source = new URL('../../botuyo-backend/src/shared/contracts/ToolConfigSchema.ts', import.meta.url)
const target = new URL('../src/schemas/toolConfig.ts', import.meta.url)
const expected = '// Generated by scripts/sync-tool-schemas.mjs; edit the backend canonical source.\n' + await readFile(source, 'utf8')
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== expected) throw new Error('Tool configuration schemas are out of sync')
} else {
  await mkdir(new URL('../src/schemas/', import.meta.url), { recursive: true })
  await writeFile(target, expected)
}
